import Foundation

enum ClipboardContent: Equatable, Sendable {
    case text(String)
    case image(Data)
    case files([URL])
}

struct ClipboardItem: Identifiable, Equatable, Sendable {
    let id: UUID
    let content: ClipboardContent
    let sourceBundleID: String?
    let copiedAt: Date
    /// Text kind (colour, link, JSON…), worked out once when copied.
    let smart: SmartText?

    init(id: UUID = UUID(), content: ClipboardContent, sourceBundleID: String?, copiedAt: Date, smart: SmartText? = nil) {
        self.id = id
        self.content = content
        self.sourceBundleID = sourceBundleID
        self.copiedAt = copiedAt
        if let smart {
            self.smart = smart
        } else if case .text(let text) = content {
            self.smart = SmartText.classify(text)
        } else {
            self.smart = nil
        }
    }
}

/// Pure clipboard-history rules: what to skip, and how the list changes.
enum ClipboardLogic {
    static let maxItems = 25
    static let maxImageBytes = 4 * 1024 * 1024
    static let maxTextLength = 100_000

    /// Pasteboard types apps set to say "don't record this" (nspasteboard.org).
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Password managers, skipped even if they don't mark their copies.
    static let ignoredApps: Set<String> = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "org.keepassxc.keepassxc",
        "com.dashlane.dashlanephonefinal",
    ]

    static func shouldRecord(types: [String], sourceBundleID: String?) -> Bool {
        if types.contains(where: privateTypes.contains) { return false }
        if let sourceBundleID, ignoredApps.contains(sourceBundleID) { return false }
        return true
    }

    /// Text worth keeping: not blank, and capped in length.
    static func normalizedText(_ text: String) -> String? {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        return text.count > maxTextLength ? String(text.prefix(maxTextLength)) : text
    }

    /// Puts the new item first. Copying the same content again moves it to the top
    /// instead of adding a duplicate.
    static func insert(_ item: ClipboardItem, into items: [ClipboardItem]) -> [ClipboardItem] {
        let rest = items.filter { $0.content != item.content }
        return Array(([item] + rest).prefix(maxItems))
    }

    /// One-line preview for a text item.
    static func preview(_ text: String, limit: Int = 140) -> String {
        let collapsed = text
            .components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        return collapsed.count > limit ? String(collapsed.prefix(limit)) + "…" : collapsed
    }
}
